import { test, expect } from '@playwright/test'

test('board, label, AI review, archive/restore and guarded deletion controls', async ({ page }, info) => {
  const boardName = 'Review board ' + info.project.name + ' ' + Date.now()
  await page.goto('/')
  await page.getByRole('button', { name: 'Create board', exact: true }).click()
  await page.getByLabel('Board name', { exact: true }).fill(boardName)
  await page.getByRole('combobox', { name: 'Visibility', exact: true }).selectOption('private')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByRole('heading', { name: boardName, exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Labels', exact: true }).click()
  await page.getByLabel('Label name', { exact: true }).fill('Review priority')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await page.getByRole('button', { name: 'New task', exact: true }).click()
  await page.getByLabel('Task title', { exact: true }).fill('Reviewable AI task')
  await page.getByRole('checkbox', { name: 'Review priority', exact: true }).check()
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await page.getByRole('button', { name: 'Reviewable AI task', exact: true }).click()
  await page.getByRole('button', { name: 'Generate with AI', exact: true }).click()
  await expect(page.getByText('AI suggestion · not saved', { exact: true })).toBeVisible()
  await page.getByLabel('Suggested checklist item 1', { exact: true }).fill('A reviewed first step')
  await page.getByRole('button', { name: 'Save reviewed checklist', exact: true }).click()
  await expect(page.getByRole('checkbox', { name: 'A reviewed first step', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Edit checklist item A reviewed first step', exact: true }).click()
  await page.getByLabel('Edit checklist text').fill('Edited after review')
  await page.getByRole('button', { name: 'Save item', exact: true }).click()
  await expect(page.getByRole('checkbox', { name: 'Edited after review', exact: true })).toBeVisible()
  page.on('dialog', (dialog) => (dialog.type() === 'prompt' ? dialog.accept(boardName) : dialog.accept()))
  await page.getByRole('dialog').getByRole('button', { name: 'Archive', exact: true }).click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await page.getByRole('button', { name: 'Archive', exact: true }).click()
  await page.getByRole('button', { name: 'Restore card', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Reviewable AI task', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Dependency map', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Dependency map', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Board settings', exact: true }).click()
  await page.getByRole('button', { name: 'Delete board', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'All boards', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: boardName, exact: true })).toHaveCount(0)
})

test('owner creates and revokes a copyable invitation', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: /Good day/ })).toBeVisible()
  if (await page.getByRole('button', { name: 'Open navigation', exact: true }).isVisible())
    await page.getByRole('button', { name: 'Open navigation', exact: true }).click()
  await page
    .getByRole('navigation', { name: 'Administration' })
    .getByRole('button', { name: 'Members', exact: true })
    .click()
  await page.getByRole('button', { name: 'Invite member', exact: true }).click()
  const email = 'guest-' + Date.now() + '@qa.invalid'
  await page.getByLabel('Email address').fill(email)
  await page.getByRole('button', { name: 'Create invitation', exact: true }).click()
  await expect(page.getByLabel('Invitation link', { exact: true })).toHaveValue(/#invite\//)
  await page.getByRole('button', { name: 'Close dialog', exact: true }).click()
  const row = page.locator('.member-row').filter({ hasText: email })
  await row.getByRole('button', { name: 'Revoke', exact: true }).click()
  await expect(row).toContainText('revoked')
})
