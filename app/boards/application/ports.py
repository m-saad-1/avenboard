"""Application-owned repository and AI interfaces."""

from typing import Protocol, Callable, TypeVar

T = TypeVar("T")


class Transaction(Protocol):
    def get(self, table: str, key: str, guard: bool = False) -> dict | None: ...
    def find(self, table: str, **filters) -> list[dict]: ...
    def put(self, table: str, row: dict) -> None: ...
    def insert(self, table: str, row: dict) -> None: ...
    def delete(self, table: str, key: str) -> None: ...
    def search_card_ids(
        self,
        board_ids: list[str],
        filters: dict,
        current_date: str,
        offset: int,
        limit: int,
    ) -> tuple[list[str], int]: ...


class Repository(Protocol):
    def run(self, work: Callable[[Transaction], T]) -> T: ...
    def semantic(
        self, board_ids: list[str], vector: list[float], limit: int
    ) -> list[dict]: ...


class Assistant(Protocol):
    def checklist(self, card: dict) -> list[str]: ...
    def summary(self, facts: dict) -> str: ...
    def recommendations(self, facts: dict) -> str: ...
    def embed(self, text: str, query: bool = False) -> list[float]: ...
